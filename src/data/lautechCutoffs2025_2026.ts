export function getLAUTECHCutoffByCourse(courseName: string): LAUTECHCourseCutoff | undefined {
  if (!courseName) return undefined;
  const clean = courseName.toLowerCase().trim();

  // Direct exact match
  const direct = LAUTECH_CUTOFFS_2025_2026.find(c => c.programme.toLowerCase() === clean);
  if (direct) return direct;

  // Fuzzy match keywords
  return LAUTECH_CUTOFFS_2025_2026.find(c => {
    const p = c.programme.toLowerCase();
    if (clean.includes("nursing") && p.includes("nursing")) return true;
    if ((clean.includes("medicine") || clean.includes("surgery") || clean.includes("mbbs")) && p === "medicine") return true;
    if ((clean.includes("med lab") || clean.includes("medical laboratory")) && p.includes("medical laboratory")) return true;
    if (clean.includes("computer science") && p === "computer science") return true;
    if (clean.includes("cyber security") && p.includes("cyber security")) return true;
    if (clean.includes("software engineering") && p.includes("computer science")) return true;
    if (clean.includes("electrical") && p.includes("electrical")) return true;
    if (clean.includes("civil") && p.includes("civil")) return true;
    if (clean.includes("mechanical") && p.includes("mechanical")) return true;
    if (clean.includes("computer eng") && p.includes("computer engineering")) return true;
    if (clean.includes("accounting") && p.includes("accounting")) return true;
    if (clean.includes("architecture") && p.includes("architecture")) return true;
    if (clean.includes("biochemistry") && p.includes("biochemistry")) return true;
    if (clean.includes("mass comm") && p.includes("mass communication")) return true;
    if (clean.includes("economics") && p === "economics") return true;
    if (clean.includes("law") && p.includes("law")) return true;
    if (clean.includes("theatre") && p.includes("theatre")) return true;
    if (clean.includes("nutrition") && p.includes("nutrition")) return true;
    if (clean.includes("physiology") && p.includes("physiology")) return true;
    if (clean.includes("anatomy") && p.includes("anatomy")) return true;
    if (clean.includes("slt") || clean.includes("science laboratory")) return p.includes("science laboratory");
    return p.includes(clean) || clean.includes(p);
  });
}

export function getLAUTECHAggregateBenchmark(utmeCutoff: number, programme?: string): number {
  const p = (programme || '').toLowerCase();
  if (p.includes('medicine') || p.includes('surgery') || p.includes('mbbs')) return 74.5;
  if (p.includes('nursing')) return 68.0;
  if (p.includes('medical laboratory')) return 65.0;
  if (p.includes('computer science')) return 64.0;
  if (p.includes('cyber security')) return 61.0;
  if (p.includes('information system') || p.includes('information technology')) return 58.5;
  if (p.includes('computer engineering') || p.includes('electrical')) return 60.0;
  if (p.includes('mechanical') || p.includes('civil')) return 58.0;
  if (p.includes('accounting') || p.includes('business')) return 57.5;
  if (p.includes('mass comm')) return 57.0;

  // Baseline formula for LAUTECH aggregate benchmark on 80:20 scale:
  // (utmeCutoff / 400 * 80) + 18.0 (typical baseline O'Level credits of 18/20)
  return Math.round(((utmeCutoff / 400) * 80 + 18.0) * 10) / 10;
}

export function getLAUTECHFaculties(): string[] {
  const faculties = new Set<string>();
  LAUTECH_CUTOFFS_2025_2026.forEach(c => faculties.add(c.faculty));
  return Array.from(faculties).sort();
}
